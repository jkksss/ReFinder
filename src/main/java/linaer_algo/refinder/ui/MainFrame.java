    private void btnCookedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCookedActionPerformed
     if (currentActiveRecipeId != -1) {
            // 1. Get the required ingredients and the user's current inventory
            java.util.List<linaer_algo.refinder.model.Ingredient> reqs = linaer_algo.refinder.database.RecipeDAO.getRecipeIngredients(currentActiveRecipeId);
            java.util.List<linaer_algo.refinder.model.Ingredient> inv = linaer_algo.refinder.database.IngredientDAO.getAllIngredients();
            
            // 2. Use our smart matching to deduct the correct items
            for(linaer_algo.refinder.model.Ingredient req : reqs) {
                String reqName = req.getName().trim().toLowerCase();
                
                // Find the matching item in the user's inventory
                for(linaer_algo.refinder.model.Ingredient myItem : inv) {
                    String invName = myItem.getName().trim().toLowerCase();
                    
                    // Basic match check (You can upgrade this to use your RabinKarp logic if preferred!)
                    if (invName.contains(reqName) || reqName.contains(invName)) {
                        // We found the match! Tell the DAO to deduct from this EXACT inventory item
                        linaer_algo.refinder.database.IngredientDAO.deductIngredient(myItem.getName(), req.getQuantity());
                        break; // Stop looking for this requirement once found
                    }
                }
            }
            
            // 3. Save to the Cooking Log Database
            String today = java.time.LocalDate.now().format(java.time.format.DateTimeFormatter.ofPattern("MMM dd, yyyy"));
            linaer_algo.refinder.model.CookingLog newLog = new linaer_algo.refinder.model.CookingLog(0, currentActiveRecipeId, "", today, 1); 
            linaer_algo.refinder.database.CookingLogDAO.addCookingLog(newLog);
            
            // 4. Show a success message to the user
            javax.swing.JOptionPane.showMessageDialog(this, "Ingredients successfully deducted from your inventory!\nAdded to Cooking Log! 🍳");
            
            // 5. Flip back to the dashboard automatically
            java.awt.CardLayout layout = (java.awt.CardLayout) pnlContent.getLayout();
            layout.show(pnlContent, "pnlDashboard");
            
            // 6. Auto-refresh the dashboard table so the inventory updates!
            btnAutoMatch.doClick(); 
        }
    }//GEN-LAST:event_btnCookedActionPerformed

    private void btnAddingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddingActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Grab the data from the UI
            String name = txtIngName.getText().trim();
            String qtyText = txtIngQty.getText().trim();
            String unit = cmbIngUnit.getSelectedItem().toString();

            // Safety check so they don't add blank stuff
            if (name.isEmpty() || qtyText.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please enter both a name and a quantity!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 2. Convert text to a number (this is where we check if they typed letters by accident)
            double qty = Double.parseDouble(qtyText);

            // 3. Send it to the database! 
            linaer_algo.refinder.database.IngredientDAO.addOrUpdateIngredient(name, qty, unit);

            // 4. Clear the text boxes so they can add the next thing easily
            txtIngName.setText("");
            txtIngQty.setText("");
            txtIngName.requestFocus(); // Puts the typing cursor back in the name box!

            // 5. Update the "Last Added" stat on your floating card
            lblRecentAdd.setText("Last Added: " + name.substring(0, 1).toUpperCase() + name.substring(1));

            // 6. Refresh the table and the rest of the stats instantly!
            buildInventoryScreen();
            // Optional: Little success pop-up
            javax.swing.JOptionPane.showMessageDialog(this, "Added to Inventory! 🥦");

        } catch (NumberFormatException e) {
            // Catches them if they type "five" instead of "5"
            javax.swing.JOptionPane.showMessageDialog(this, "Quantity must be a number!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddingActionPerformed

